"""
Re-skin the two article hubs onto the v4 brand-book template.

    python3 tools/reskin_blog_hubs.py --dry-run     # report, write nothing
    python3 tools/reskin_blog_hubs.py               # rewrite both hubs
    python3 tools/reskin_blog_hubs.py --lang ar     # one hub
    python3 tools/reskin_blog_hubs.py --out /tmp/p  # write elsewhere

`public_html/blog/index.html` (EN) and `public_html/blog-ar/index.html` (AR)
were the last two pages still on the old dark Tailwind-CDN skin, which left
them looking like a different site from the 300 articles they link to. Both are
rewritten IN PLACE - the URLs are indexed and every article's chrome links back
to them.

Where the content comes from
----------------------------
Nothing on either hub is typed by hand. Every card's headline, description,
category, hero image, date and reading time is read off the published article
at build time, so the hub cannot drift from the corpus: publish an article and
re-run this, and it appears. The old hubs carried the same 150 cards as literal
markup, which is why they had to be regenerated by `update_blog_hubs.py` and
why a stale card could sit there unnoticed.

What is preserved
-----------------
Both canonicals, the Organization/ProfessionalService JSON-LD block (address,
CR, phone, geo and sameAs byte for byte from the old hubs), the GA measurement
id, and the full set of 150 article links per language.

What is fixed
-------------
  * The English hub's meta description was written in Arabic. Both hubs now
    describe themselves in their own language.
  * Neither hub declared hreflang, so the EN and AR archives of the same
    corpus competed instead of pairing. Both now point at each other, with
    x-default on the English one.
  * The category filter ran off `update_blog_hubs.py`'s CATEGORY_MAP, which
    knew 25 of the 70+ category strings in use; everything it did not know -
    about half the corpus - silently fell into "Implementation & Automation".
    Buckets are now derived by rule (see BUCKET_RULES) and, because a bucket is
    resolved from the English article and then applied to its Arabic twin, the
    same piece files under the same heading in both languages.
  * Search and filter were separate behaviours that overwrote each other. They
    now compose, and both degrade to "every article listed, newest first".

What is removed
---------------
The Tailwind CDN script, the old dark skin, the FOUC overlay, and
`/js/aiden-chat.js`. The widget is dropped for the same reason the articles
dropped it: `blog_chrome.footer` already puts a WhatsApp action button in the
bottom corner and Aiden's launcher pins to that same corner, so the two overlap.
Note that `tools/add_aiden_widget.py` will put the script tag back on its next
run, on these pages and on all 150 articles.
"""
