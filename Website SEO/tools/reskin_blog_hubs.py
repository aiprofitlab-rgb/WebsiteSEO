def _esc(s):
    """Unescape first: the source pages mix raw characters with named entities
    inside the same attribute, and escaping those directly would double-encode
    the ampersand and publish the literal text."""
    return _html.escape(_html.unescape(s or ""), quote=True)


def _kicker(e, lang, labels):
    """The article's own category is more specific than its bucket, so it is
    what the card shows. On the Arabic hub a category left in English is
    replaced by the bucket's Arabic label rather than printed as-is."""
    cat = e["cat"].strip()
    if cat and lang == "ar" and not re.search(r"[؀-ۿ]", cat):
        cat = ""
    return _html.unescape(cat) if cat else _html.unescape(labels[e["bucket"]])


def _mins(e, lang):
    return max(1, round(e["words"] / WPM[lang]))


def card(e, lang, labels, t, hidden, feat=False):
    """One archive card. `data-s` is the search index for this article: the
    fields a reader would plausibly type against, in one attribute, so the
    filter never has to touch the DOM text.

    The newest article gets a card here as well as the display panel above,
    marked `data-feat`. Without it the piece most likely to be looked for is
    the one piece the search cannot return, because the panel is not part of
    the filtered list. The card is suppressed exactly while the panel shows it.
    """
    idx = " ".join((e["title"], e["tag_title"], e["desc"], e["cat"], e["kw"])).lower()
    return (
        '<a class="post"%s href="%s" data-cat="%s" data-s="%s"%s>'
        '<div class="shot"><img src="%s" alt="" loading="lazy" decoding="async" '
        'width="420" height="236"></div>'
        '<div class="txt">'
        '<p class="kicker">%s</p>'
        '<h3>%s</h3>'
        '<p>%s</p>'
        '<span class="stamp"><time datetime="%s">%s</time><span>%d %s</span></span>'
        '</div></a>'
        % (' data-feat=""' if feat else "",
           _esc(e["url"]), e["bucket"], _esc(re.sub(r"\s+", " ", idx)),
           " hidden" if hidden else "",
           _esc(e["img"]), _esc(_kicker(e, lang, labels)), _esc(e["title"]),
           _esc(e["desc"]), _esc(e["date"]), _esc(C.fmt_date(e["date"], lang)),
           _mins(e, lang), t["read"])
    )


