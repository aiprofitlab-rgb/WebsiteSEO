def bucket(entry):
    """Resolve one article to one filter key.

    The category is the strongest signal, but seven articles carry none and a
    number carry one so generic it says nothing ("AI Tools"), so the headline
    and the page's own keywords are searched as a fallback before the default.
    """
    for haystack in (entry["cat"].lower(),
                     " ".join((entry["title"], entry["tag_title"], entry["kw"])).lower()):
        if not haystack.strip():
            continue
        for key, words in BUCKET_RULES:
            if any(w in haystack for w in words):
                return key
    return "systems"


