def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lang", choices=["en", "ar"], help="only one hub")
    ap.add_argument("--out", help="write into this directory instead of in place")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    css_href, js_href = build_assets(write=not a.dry_run)
    print(f"  assets: {css_href}  {js_href}")

    # Buckets are resolved once, on the English article, then applied to its
    # Arabic twin. Deriving them separately per language would need the rule
    # table written twice and would let the same piece file under two different
    # headings in the two archives.
    src = {lang: read_articles(lang) for lang in ("en", "ar")}
    keys = {}
    for slug, e in src["en"].items():
        keys[slug] = bucket(e)
    for slug, e in src["ar"].items():
        e["bucket"] = keys.get(slug) or bucket(e)
    for slug, e in src["en"].items():
        e["bucket"] = keys[slug]

    for lang in ([a.lang] if a.lang else ["en", "ar"]):
        entries = sorted(src[lang].values(),
                         key=lambda e: (e["date"], e["slug"]), reverse=True)
        html = render(lang, entries, css_href, js_href)
        dest = HUBS[lang]["file"]
        if a.out:
            dest = pathlib.Path(a.out) / ("blog" if lang == "en" else "blog-ar") / "index.html"
        spread = {}
        for e in entries:
            spread[e["bucket"]] = spread.get(e["bucket"], 0) + 1
        note = "  ".join("%s:%d" % kv for kv in sorted(spread.items()))
        if a.dry_run:
            print(f"  would write {HUBS[lang]['file'].relative_to(ROOT)}  "
                  f"{len(html)/1024:.0f} KB  {len(entries)} articles  [{note}]")
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(html, encoding="utf-8")
            shown = dest.relative_to(ROOT) if a.out is None else dest
            print(f"  wrote {shown}  {len(html)/1024:.0f} KB  "
                  f"{len(entries)} articles  [{note}]")


if __name__ == "__main__":
    main()
