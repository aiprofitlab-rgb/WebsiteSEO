# Reading the corpus
# --------------------------------------------------------------------------
def _meta(head, name, prop=False):
    attr = "property" if prop else "name"
    m = re.search(r'<meta %s="%s" content="([^"]*)"' % (attr, name), head)
    return _html.unescape(m.group(1)).strip() if m else ""


def read_articles(lang):
    """One dict per published article, keyed by slug."""
    out = {}
    for f in sorted((BLOG / lang).glob("*.html")):
        src = f.read_text(encoding="utf-8")
        head = src[:src.find("</head>")] if "</head>" in src else src[:12000]

        m = re.search(r"<title>(.*?)</title>", head, re.S)
        tag_title = _html.unescape(m.group(1)).strip() if m else f.stem
        tag_title = re.sub(r"\s*\|\s*AI Profit Lab.*$", "", tag_title).strip()

        # The card shows the article's own <h1>, not its <title>. Six English
        # articles carry a <title> that was cut off mid-word by whatever wrote
        # them ("Arabic | AI Profit Lab", "How Businesses in Dubai Are Using
        # Wh... |"), and all 300 have an intact <h1>. The <title> is also the
        # SEO string rather than the headline, so even where it is whole the
        # <h1> is the better card text. The <title> is kept for the search
        # index, where its extra keywords are worth something.
        m = re.search(r'<h1 class="h1">(.*?)</h1>', src, re.S)
        title = _html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else ""
        if not title:
            title = tag_title

        img = _meta(head, "og:image", prop=True)
        if img.startswith(SITE):
            img = img[len(SITE):]

        date = _meta(head, "article:published_time", prop=True)
        if not re.match(r"\d{4}-\d{2}-\d{2}$", date):
            m = re.match(r"(\d{4}-\d{2}-\d{2})", f.stem)
            date = m.group(1) if m else ""

        body = re.search(r'<article class="prose">(.*?)</article>', src, re.S)
        words = len(re.sub(r"<[^>]+>", " ", body.group(1)).split()) if body else 0

        out[f.stem] = {
            "slug": f.stem,
            "title": title,
            "tag_title": tag_title,
            "desc": _meta(head, "description"),
            "kw": _meta(head, "keywords"),
            "cat": _meta(head, "category"),
            "img": img or "/blog/images/default.png",
            "date": date,
            "words": words,
            # Always the trailing-slash form. 242 of the 300 articles declare a
            # canonical without one, and .htaccess 301s that shape to this one,
            # so linking the canonical as written would send every reader and
            # every crawler through a redirect on the way in.
            "url": "/blog/%s/%s/" % (lang, f.stem),
        }
    return out


