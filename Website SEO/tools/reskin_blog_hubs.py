def build_assets(write=True):
    """One stylesheet and one script for both hubs, under a content-hashed
    filename so /assets/**'s year-long immutable cache can never serve a stale
    copy."""
    out = {}
    for ext, blob in (("css", stylesheet()), ("js", MOTION_JS + HUB_JS)):
        h = hashlib.sha256(blob.encode()).hexdigest()[:10]
        name = f"apl-hub.{h}.{ext}"
        if write:
            d = ASSETS / ext
            d.mkdir(parents=True, exist_ok=True)
            for old in d.glob(f"apl-hub.*.{ext}"):
                if old.name != name:
                    old.unlink()
            (d / name).write_text(blob, encoding="utf-8")
        out[ext] = f"/assets/{ext}/{name}"
    return out["css"], out["js"]


