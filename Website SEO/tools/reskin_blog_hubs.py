def schema(lang, entries):
    """A Blog node for the hub, a breadcrumb, and the list itself.

    The ItemList carries position and url only. The headline and image already
    sit on the target page and repeating them here is two places to go stale;
    what the list adds that the markup does not is the ORDER, which is the one
    thing a crawler cannot infer from a grid.
    """
    t, u = T[lang], HUBS[lang]["url"]
    items = ",".join(
        '{"@type":"ListItem","position":%d,"url":"%s"}' % (i + 1, SITE + e["url"])
        for i, e in enumerate(entries))
    home = SITE + (C.URLS[lang]["home"])
    return f"""<script type="application/ld+json">
{{"@context":"https://schema.org","@graph":[
{{"@type":"Blog","@id":"{u}#blog","name":"{_html.unescape(t['schema_name'])}","url":"{u}",
  "inLanguage":"{'ar' if lang == 'ar' else 'en'}","description":"{_esc(t['desc'] % len(entries))}",
  "publisher":{{"@type":"Organization","name":"AI Profit Lab","legalName":"Lotus Gulf International","url":"{SITE}"}}}},
{{"@type":"BreadcrumbList","itemListElement":[
  {{"@type":"ListItem","position":1,"name":"{C.T[lang]['crumb_home']}","item":"{home}"}},
  {{"@type":"ListItem","position":2,"name":"{C.T[lang]['crumb_blog']}","item":"{u}"}}]}},
{{"@type":"ItemList","@id":"{u}#articles","name":"{_html.unescape(t['schema_name'])}",
  "numberOfItems":{len(entries)},"itemListOrder":"https://schema.org/ItemListOrderDescending",
  "itemListElement":[{items}]}}
]}}
</script>
"""


def header(lang):
    """`blog_chrome.header` sends the language toggle to the other language's
    HOME page. From an article hub the useful destination is the other hub, so
    the two anchors that carry it are swapped by exact string - a blind replace
    of the href would also hit the logo, which points at the same "/" on the
    English pages."""
    out = C.header(lang)
    u, t = C.URLS[lang], C.T[lang]
    other_lang = "ar" if lang == "en" else "en"
    other_hub = HUBS[other_lang]["url"].replace(SITE, "")
    for old, new in (
        ('<a class="lnk" href="%s" lang="%s">%s</a>' % (u["other"], other_lang, t["other_lang"]),
         '<a class="lnk" href="%s" lang="%s">%s</a>' % (other_hub, other_lang, t["other_lang"])),
        ('<a href="%s" lang="%s"><em>07</em>%s</a>' % (u["other"], other_lang, t["other_lang"]),
         '<a href="%s" lang="%s"><em>07</em>%s</a>' % (other_hub, other_lang, t["other_lang"])),
    ):
        if old not in out:
            raise SystemExit("header(): language toggle markup changed in blog_chrome; "
                             "update reskin_blog_hubs.header()")
        out = out.replace(old, new)
    return out


